/* =========================================================
   STATE
   ========================================================= */

let currentSearch = "";
let currentStatus = "all";


/* =========================================================
   SEARCH HELPERS
   ========================================================= */

function personText(person) {

    return [

        person.name,
        person.rank,
        person.callsign,
        person.serviceNumber,
        person.status,
        person.unit,
        person.appointment,
        person.joinDate,
        person.note

    ]
        .filter(Boolean)
        .join(" ")
        .toLowerCase();

}


function matchesPerson(id) {

    const person = personnel[id];

    if (!person) {
        return false;
    }

    if (
        currentStatus !== "all" &&
        person.status !== currentStatus
    ) {
        return false;
    }

    if (!currentSearch) {
        return true;
    }

    return personText(person)
        .includes(currentSearch);

}


function countVisiblePeople() {

    return Object.keys(personnel)
        .filter(matchesPerson)
        .length;

}


/* =========================================================
   TREE SEARCH
   ========================================================= */

function nodeContainsVisiblePerson(node) {

    if (!node) {
        return false;
    }

    if (
        node.personnel &&
        node.personnel.some(matchesPerson)
    ) {
        return true;
    }

    return Boolean(
        node.children &&
        node.children.some(
            nodeContainsVisiblePerson
        )
    );

}


function nodeMatchesSearch(node) {

    if (!node) {
        return false;
    }

    if (
        !currentSearch &&
        currentStatus === "all"
    ) {
        return true;
    }

    const titleMatches =
        (node.title || "")
            .toLowerCase()
            .includes(currentSearch);

    if (
        titleMatches &&
        currentStatus === "all"
    ) {
        return true;
    }

    return nodeContainsVisiblePerson(node);

}


/* =========================================================
   PERSONNEL ENTRY
   ========================================================= */

function createPersonnelEntry(id) {

    const person = personnel[id];

    if (
        !person ||
        !matchesPerson(id)
    ) {
        return null;
    }


    const entry =
        document.createElement("button");

    entry.type = "button";

    entry.className =
        "personnel-entry";

    entry.setAttribute(
        "aria-label",
        `Open personnel record for ${person.name}`
    );


    const index =
        document.createElement("span");

    index.className =
        "personnel-index";

    index.textContent =
        "—";


    const rank =
        document.createElement("span");

    rank.className =
        "personnel-rank";

    rank.textContent =
        person.rank || "—";


    const nameBlock =
        document.createElement("div");

    nameBlock.className =
        "personnel-name-block";


    const name =
        document.createElement("div");

    name.className =
        "personnel-name";

    name.textContent =
        person.name || "—";


    const callsign =
        document.createElement("div");

    callsign.className =
        "personnel-callsign";

    callsign.textContent =
        person.callsign || "—";


    nameBlock.append(
        name,
        callsign
    );


    const appointment =
        document.createElement("div");

    appointment.className =
        "personnel-appointment";


    const appointmentText =
        document.createElement("span");

    appointmentText.textContent =
        person.appointment || "—";


    appointment.appendChild(
        appointmentText
    );


    const status =
        document.createElement("span");

    status.className =
        `personnel-status ${
            person.status || "inactive"
        }`;

    status.textContent =
        (
            person.status ||
            "inactive"
        ).toUpperCase();


    entry.append(
        index,
        rank,
        nameBlock,
        appointment,
        status
    );


    entry.addEventListener(
        "click",
        () => openProfile(person)
    );


    return entry;

}


/* =========================================================
   PERSONNEL LIST
   ========================================================= */

function renderPersonnelList(
    ids,
    container
) {

    const list =
        document.createElement("div");

    list.className =
        "personnel-list";


    let count = 0;


    ids.forEach(id => {

        const entry =
            createPersonnelEntry(id);

        if (!entry) {
            return;
        }

        count++;

        entry.querySelector(
            ".personnel-index"
        ).textContent =
            String(count).padStart(2, "0");

        list.appendChild(entry);

    });


    if (!count) {
        return null;
    }


    container.appendChild(list);

    return list;

}


/* =========================================================
   COMMAND TREE
   ========================================================= */

function renderCommandNode(
    node,
    container,
    depth = 0
) {

    if (!node) {
        return;
    }


    const wrapper =
        document.createElement("div");

    wrapper.className =
        `roster-node roster-depth-${depth}`;


    const header =
        document.createElement("div");

    header.className =
        "roster-node-header";


    const title =
        document.createElement("span");

    title.className =
        "roster-node-title";

    title.textContent =
        node.title || "—";


    header.appendChild(title);


    const visiblePeople =
        (node.personnel || [])
            .filter(matchesPerson);


    if (visiblePeople.length) {

        const people =
            document.createElement("span");

        people.className =
            "roster-node-personnel";

        people.textContent =
            `— ${
                visiblePeople
                    .map(
                        id =>
                            personnel[id].name
                    )
                    .join(", ")
            }`;

        header.appendChild(people);

    }


    wrapper.appendChild(header);


    if (node.note) {

        const note =
            document.createElement("div");

        note.className =
            "roster-node-note";

        note.textContent =
            node.note;

        wrapper.appendChild(note);

    }


    const visibleChildren =
        (node.children || [])
            .filter(nodeMatchesSearch);


    if (visibleChildren.length) {

        const children =
            document.createElement("div");

        children.className =
            "roster-node-children";


        visibleChildren.forEach(
            child => {

                renderCommandNode(
                    child,
                    children,
                    depth + 1
                );

            }
        );


        wrapper.appendChild(children);

    }


    container.appendChild(wrapper);

}


/* =========================================================
   UNIT
   ========================================================= */

function renderUnit(
    unit,
    container
) {

    const section =
        document.createElement("section");

    section.className =
        "roster-subunit";


    const heading =
        document.createElement("div");

    heading.className =
        "subunit-heading";


    const title =
        document.createElement("span");

    title.className =
        "subunit-title";

    title.textContent =
        `${unit.abbreviation} / ${unit.title}`;


    heading.appendChild(title);

    section.appendChild(heading);


    if (
        unit.command &&
        nodeMatchesSearch(unit.command)
    ) {

        const command =
            document.createElement("div");

        command.className =
            "unit-command-tree";


        renderCommandNode(
            unit.command,
            command
        );


        section.appendChild(command);

    }


    renderPersonnelList(
        units[unit.id] || [],
        section
    );


    if (
        section.querySelector(
            ".personnel-list"
        ) ||
        section.querySelector(
            ".roster-node"
        )
    ) {

        container.appendChild(section);

    }

}


/* =========================================================
   GENERIC ROSTER NODE
   ========================================================= */

function renderNode(
    node,
    container,
    depth = 0
) {

    if (!nodeMatchesSearch(node)) {
        return;
    }


    if (node.type === "unit") {

        renderUnit(
            node,
            container
        );

        return;

    }


    const wrapper =
        document.createElement("section");

    wrapper.className =
        [
            "roster-node",
            `roster-depth-${depth}`,
            `roster-type-${node.type}`
        ].join(" ");


    const header =
        document.createElement("div");

    header.className =
        "roster-node-header";


    const title =
        document.createElement("span");

    title.className =
        "roster-node-title";

    title.textContent =
        node.title || "—";


    header.appendChild(title);


    const visiblePeople =
        (node.personnel || [])
            .filter(matchesPerson);


    if (visiblePeople.length) {

        const people =
            document.createElement("span");

        people.className =
            "roster-node-personnel";

        people.textContent =
            `— ${
                visiblePeople
                    .map(
                        id =>
                            personnel[id].name
                    )
                    .join(", ")
            }`;

        header.appendChild(people);

    }


    wrapper.appendChild(header);


    const visibleChildren =
        (node.children || [])
            .filter(nodeMatchesSearch);


    if (visibleChildren.length) {

        const children =
            document.createElement("div");

        children.className =
            "roster-node-children";


        visibleChildren.forEach(
            child => {

                renderNode(
                    child,
                    children,
                    depth + 1
                );

            }
        );


        wrapper.appendChild(children);

    }


    container.appendChild(wrapper);

}


/* =========================================================
   MAIN RENDER
   ========================================================= */

function renderRoster() {

    const container =
        document.getElementById(
            "roster-list"
        );

    const empty =
        document.getElementById(
            "roster-empty"
        );


    if (!container) {
        return;
    }


    container.replaceChildren();


    roster.forEach(
        node => {

            renderNode(
                node,
                container
            );

        }
    );


    const count =
        countVisiblePeople();


    const searchCount =
        document.getElementById(
            "search-count"
        );


    if (searchCount) {

        searchCount.textContent =
            `${count} PERSONNEL`;

    }


    if (empty) {

        empty.classList.toggle(
            "hidden",
            count !== 0
        );

    }

}


/* =========================================================
   SEARCH
   ========================================================= */

function setupSearch() {

    const search =
        document.getElementById(
            "roster-search"
        );


    if (!search) {
        return;
    }


    search.addEventListener(
        "input",
        event => {

            currentSearch =
                event.target.value
                    .trim()
                    .toLowerCase();

            renderRoster();

        }
    );

}


/* =========================================================
   FILTERS
   ========================================================= */

function setupFilters() {

    const filters =
        document.querySelectorAll(
            ".roster-filter"
        );


    filters.forEach(
        filter => {

            filter.addEventListener(
                "click",
                () => {

                    currentStatus =
                        filter.dataset.status ||
                        "all";


                    filters.forEach(
                        other => {

                            other.classList.toggle(
                                "active",
                                other === filter
                            );

                        }
                    );


                    renderRoster();

                }
            );

        }
    );

}


/* =========================================================
   PROFILE
   ========================================================= */

function openProfile(person) {

    const modal =
        document.getElementById(
            "personnel-modal"
        );


    if (!modal) {
        return;
    }


    const fields = {

        "profile-rank":
            person.rank,

        "profile-name":
            person.name,

        "profile-callsign":
            person.callsign,

        "profile-service-number":
            person.serviceNumber,

        "profile-status":
            (
                person.status ||
                "active"
            ).toUpperCase(),

        "profile-unit":
            person.unit,

        "profile-appointment":
            person.appointment,

        "profile-join-date":
            person.joinDate,

        "profile-note":
            person.note

    };


    Object.entries(fields)
        .forEach(
            ([id, value]) => {

                const element =
                    document.getElementById(id);

                if (element) {

                    element.textContent =
                        value || "—";

                }

            }
        );


    modal.classList.add("open");


    document.getElementById(
        "profile-close"
    )?.focus();

}


/* =========================================================
   CLOSE PROFILE
   ========================================================= */

function closeProfile() {

    const modal =
        document.getElementById(
            "personnel-modal"
        );


    if (!modal) {
        return;
    }


    modal.classList.remove(
        "open"
    );

}


